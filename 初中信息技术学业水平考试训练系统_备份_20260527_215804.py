            op = operation_questions[row]
            detail = f"【{op['type']}】\n题目:{op['question']}\n"
            if 'options' in op:
                detail += "\n选项:\n" + "\n".join(op['options']) + "\n"
            detail += f"\n参考答案:{op['answer']}"
            self.op_detail.setText(detail)


