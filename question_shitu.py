def _make_question(
    q_id: str,
    question: str,
    options: List[str],
    answer: int,
    explanation: str,
    image: str,
    difficulty: str = "medium",
    topic: str = "识图题"
) -> Dict:
    """构造标准识图题目"""
    return {
        "id": q_id,
        "type": "judge" if not options else "select",
        "question": question,
        "options": options,
        "answer": answer,          # judge题answer为True/False，select题answer为0-based索引
        "explanation": explanation,
        "image": image,            # 相对路径或URL
        "difficulty": difficulty,
        "topic": topic,
    }


