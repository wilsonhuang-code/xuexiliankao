"""
连线题题库模块 v1.0
为生地会考系统增加连线题/匹配题题型
题型说明：
- match: 匹配题（左侧选项与右侧选项一一对应）
- line: 连线题（左侧项目与右侧项目一一连线）
"""

from typing import List, Dict, Tuple
import random


def _make_match_question(
    q_id: str,
    question: str,
    left_items: List[str],
    right_items: List[str],
    matches: List[Tuple[int, int]],
    explanation: str,
    difficulty: str = "medium",
    topic: str = "综合"
) -> Dict:
    """构造匹配题/连线题

    Args:
        q_id: 题目ID
        question: 题目描述
        left_items: 左侧项目列表
        right_items: 右侧项目列表（打乱顺序显示）
        matches: 正确答案配对列表 [(左索引, 右索引), ...]
        explanation: 解析
        difficulty: 难度
        topic: 知识点
    """
    # 正确配对的映射：{左索引: 右索引}
    correct_map = {left: right for left, right in matches}
    # 打乱右侧选项顺序（用于显示）
    shuffled_right = right_items.copy()
    random.shuffle(shuffled_right)

    return {
        "id": q_id,
        "type": "match",
        "question": question,
        "left_items": left_items,
        "right_items": right_items,  # 原始顺序（用于批改）
        "display_right": shuffled_right,  # 打乱后显示（用户看到）
        "correct_map": correct_map,  # 正确答案映射 {左索引: 右索引}
        "explanation": explanation,
        "difficulty": difficulty,
        "topic": topic,
    }


