    def begin(self):
        self.questions = []
        for sub in ["math", "english", "physics"]:
            sub_q = random.sample(ALL_QUESTIONS[sub], min(3, len(ALL_QUESTIONS[sub])))
            self.questions.extend([(sub, q) for q in sub_q])
        self.index = 0
        self.score = 0
        self.show_question()

    def show_question(self):
        if self.index >= len(self.questions):
            self.finish()
            return
        self.layout.clear_widgets()
        sub, q = self.questions[self.index]
        sub_names = {"math": "数学", "english": "英语", "physics": "物理"}
        self.layout.add_widget(make_label(f"第{self.index+1}/{len(self.questions)}题 [{sub_names.get(sub,sub)}]", self.app, font_size=16, color_key="highlight", size_hint=(1, None)))
        self.layout.add_widget(make_label(f"当前得分: {self.score}", self.app, font_size=14, color_key="text2", size_hint=(1, None)))
        self.layout.add_widget(make_label(q['text'], self.app, font_size=16, size_hint=(1, None)))
        self.input = TextInput(hint_text="输入答案...", size_hint=(1, None), height=dp(44), font_size=sp(16), multiline=False)
        self.input.bind(on_text_validate=lambda inst: self.submit())
        self.layout.add_widget(self.input)
        self.layout.add_widget(make_btn("提交", lambda inst: self.submit(), self.app, bg_key="primary", height=44))
        self.feedback = make_label("", self.app, font_size=15, size_hint=(1, None))
        self.feedback.height = dp(50)
        self.layout.add_widget(self.feedback)

    def submit(self):
        if self.index >= len(self.questions):
            return
        sub, q = self.questions[self.index]
        user = self.input.text.strip()
        correct = (q["answer"].lower() in user.lower()) or (user.lower() == q["answer"].lower())
        if correct:
            self.score += 10
            if sub in ["math", "physics"]:
                self.app.reward.add_star(sub)
            else:
                self.app.reward.add_english_reward()
            self.feedback.text = f"正确 +10分! 讲解: {q['explain']}"
            self.feedback.color = hex_to_rgba(self.app.get_theme()["success"])
        else:
            self.feedback.text = f"错误。正确: {q['answer']}"
            self.feedback.color = hex_to_rgba(self.app.get_theme()["error"])
            add_mistake(sub, q["text"], user, q["answer"], q["explain"])
        self.index += 1
        Clock.schedule_once(lambda dt: self.show_question(), 1.5)

    def finish(self):
        self.layout.clear_widgets()
        total = len(self.questions) * 10
        self.layout.add_widget(make_label("考试结束", self.app, font_size=22, bold=True, color_key="accent", halign="center", size_hint=(1, None)))
        self.layout.add_widget(make_label(f"得分: {self.score}/{total}", self.app, font_size=20, bold=True, color_key="primary", halign="center", size_hint=(1, None)))
        self.layout.add_widget(Label(size_hint_y=1))
        self.layout.add_widget(make_btn("重新考试", lambda inst: self.show_start(), self.app, bg_key="primary", height=48))
        self.layout.add_widget(make_btn("返回首页", self.app.go_home, self.app, height=44, font_size=14))

