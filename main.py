class StudyTimer:
    def __init__(self, reward_sys):
        self.reward = reward_sys
        self.load_data()
        self.start_time = None
        self.current_page = None
    def load_data(self):
        if os.path.exists(STUDY_TIME_FILE):
            with open(STUDY_TIME_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                self.today = data.get("today", date.today().isoformat())
                self.total_seconds = data.get("total_seconds", 0)
                self.sessions = data.get("sessions", [])
        else:
            self.today = date.today().isoformat()
            self.total_seconds = 0
            self.sessions = []
    def save_data(self):
        with open(STUDY_TIME_FILE, "w", encoding="utf-8") as f:
            json.dump({"today": self.today, "total_seconds": self.total_seconds, "sessions": self.sessions}, f, ensure_ascii=False, indent=2)
    def start_page(self, page_name=""):
        if self.today != date.today().isoformat():
            self.today = date.today().isoformat()
            self.total_seconds = 0
            self.sessions = []
        self.start_time = datetime.now()
        self.current_page = page_name
    def stop_page(self):
        if self.start_time:
            elapsed = (datetime.now() - self.start_time).total_seconds()
            self.total_seconds += elapsed
            self.sessions.append({"page": self.current_page, "seconds": int(elapsed), "time": self.start_time.strftime("%H:%M")})
            self.start_time = None
            # 满3小时给星
            if self.total_seconds >= 3 * 3600 and self.total_seconds - elapsed < 3 * 3600:
                self.reward.add_star("timer")
            self.save_data()
    def get_today_hours(self):
        if self.today != date.today().isoformat():
            return 0.0
        extra = (datetime.now() - self.start_time).total_seconds() if self.start_time else 0
        return (self.total_seconds + extra) / 3600.0
    def get_remaining_seconds(self):
        target = 3 * 3600
        extra = (datetime.now() - self.start_time).total_seconds() if self.start_time else 0
        used = self.total_seconds + extra
        return max(0, target - used)

