# ====== 通用UI组件 ======
class BGBoxLayout(BoxLayout):
    """带背景色的BoxLayout"""
    def __init__(self, app_ref, **kwargs):
        super().__init__(**kwargs)
        self.app_ref = app_ref
        self.bind(size=self._update_bg, pos=self._update_bg)
    def _update_bg(self, *args):
        t = self.app_ref.get_theme()
        self.canvas.before.clear()
        with self.canvas.before:
            Color(*hex_to_rgba(t["bg"]))
            Rectangle(pos=self.pos, size=self.size)

def make_label(text, app_ref, font_size=16, bold=False, color_key="fg", halign="left", valign="middle", size_hint=(1, None)):
    t = app_ref.get_theme()
    lbl = Label(text=text, font_size=sp(font_size), bold=bold, size_hint=size_hint,
                color=hex_to_rgba(t[color_key]), halign=halign, valign=valign,
                height=dp(font_size * 2.5))
    return lbl

def make_btn(text, callback, app_ref, bg_key="btn", text_color_key="fg", height=48, font_size=16):
    t = app_ref.get_theme()
    bg = t.get(bg_key, t["btn"])
    if isinstance(bg, str) and bg.startswith('#'):
        bg_rgba = hex_to_rgba(bg)
    else:
        bg_rgba = (0.15, 0.15, 0.3, 1)
    tc = hex_to_rgba(t[text_color_key])
    btn = Button(text=text, font_size=sp(font_size), bold=True,
                 background_color=bg_rgba, color=tc,
                 size_hint=(1, None), height=dp(height))
    btn.bind(on_press=callback)
    return btn

