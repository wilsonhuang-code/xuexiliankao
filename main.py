class TrainingScreen(Screen):
    def __init__(self, app_ref, **kw):
        super().__init__(**kw)
        self.app = app_ref
        self.trainer = None
        self.subject = None
        self.layout = BGBoxLayout(app_ref, orientation='vertical', padding=dp(15), spacing=dp(8))
        self.add_widget(self.layout)

    def set_trainer(self, trainer, subject):
        self.trainer = trainer
        self.subject = subject
        self.show_question()

    def show_question(self):
        self.layout.clear_widgets()
        if self.trainer is None:
            self.layout.add_widget(make_label("未选择学科", self.app, font_size=18))
            return

        # 等级和进度
        top = BoxLayout(orientation='horizontal', size_hint=(1, None), height=dp(30))
        level_stars = "★" * self.trainer.level + "☆" * (3 - self.trainer.level)
        top.add_widget(make_label(f"难度: {level_stars}", self.app, font_size=14, color_key="highlight"))
        top.add_widget(make_label(f"连续正确: {self.trainer.correct_in_level}/3", self.app, font_size=14, color_key="text2", halign="right"))
        self.layout.add_widget(top)

        # 题目
        while True:
            result = self.trainer.next()
            typ = result[0]
            if typ == "question":
                q = result[1]
                self.layout.add_widget(make_label(f"第{len(self.trainer.mastered)+1}题: {q['text']}", self.app, font_size=16, color_key="fg", size_hint=(1, None)))
                self.layout.add_widget(Label(size_hint=(1, None), height=dp(8)))
                self.input = TextInput(hint_text="输入答案...", size_hint=(1, None), height=dp(44),
                                       font_size=sp(16), multiline=False)
                self.input.bind(on_text_validate=lambda inst: self.submit())
                self.layout.add_widget(self.input)
                self.layout.add_widget(make_btn("提交", lambda inst: self.submit(), self.app, bg_key="primary", height=44))
                self.feedback = make_label("", self.app, font_size=15, color_key="fg", size_hint=(1, None))
                self.feedback.height = dp(60)
                self.layout.add_widget(self.feedback)
                break
            elif typ == "upgrade":
                level = result[1]
                self.app.reward.add_points(100)
                self.layout.add_widget(make_label(f"升级到难度{level}星! +100积分", self.app, font_size=18, bold=True, color_key="success"))
            elif typ == "complete":
                self.layout.add_widget(make_label("完成本学科所有题目!", self.app, font_size=20, bold=True, color_key="success", halign="center"))
                break

        self.layout.add_widget(Label(size_hint_y=1))
        self.layout.add_widget(make_btn("结束训练", self.app.go_train_subject, self.app, height=44, font_size=14))

    def submit(self):
        if self.trainer is None or self.trainer.current is None:
            return
        user = self.input.text.strip()
        if not user:
            self.feedback.text = "请输入答案"
            return
        correct, q = self.trainer.check(user)
        if correct:
            if self.subject in ["math", "physics"]:
                self.app.reward.add_star(self.subject)
            else:
                self.app.reward.add_english_reward()
            self.feedback.text = f"正确! 讲解: {q['explain']}"
            self.feedback.color = hex_to_rgba(self.app.get_theme()["success"])
        else:
            self.feedback.text = f"错误。正确答案: {q['answer']}\n讲解: {q['explain']}"
            self.feedback.color = hex_to_rgba(self.app.get_theme()["error"])
            add_mistake(self.subject, q["text"], user, q["answer"], q["explain"])
        # 1秒后下一题
        Clock.schedule_once(lambda dt: self.show_question(), 1.5)

