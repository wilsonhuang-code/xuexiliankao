class WordMastery:
    def __init__(self, word_list):
        self.word_list = word_list
        self.records = self.load()
        self.intervals = [1, 2, 4, 7, 15]
    def load(self):
        default_rec = {"mastered": False, "review_count": 0, "last_review": None, "next_review": None, "correct_streak": 0}
        rec = {w: dict(default_rec) for w, _, _ in self.word_list}
        if os.path.exists(WORD_MASTERY_FILE):
            try:
                with open(WORD_MASTERY_FILE, "r", encoding="utf-8") as f:
                    saved = json.load(f)
                for w, data in saved.items():
                    if w in rec:
                        rec[w].update(data)
            except: pass
        return rec
    def save(self):
        with open(WORD_MASTERY_FILE, "w", encoding="utf-8") as f:
            json.dump(self.records, f, ensure_ascii=False, indent=2)
    def get_due(self, today=None):
        if today is None:
            today = datetime.now().strftime("%Y-%m-%d")
        due = []
        for w, rec in self.records.items():
            if rec["mastered"]:
                continue
            if rec["next_review"] is None or rec["next_review"] <= today:
                due.append(w)
        return due
    def mark(self, word, correct):
        rec = self.records[word]
        rec["last_review"] = datetime.now().strftime("%Y-%m-%d")
        if correct:
            rec["correct_streak"] += 1
            rec["review_count"] += 1
            idx = min(rec["correct_streak"] - 1, len(self.intervals) - 1)
            next_date = (datetime.now() + timedelta(days=self.intervals[idx])).strftime("%Y-%m-%d")
            rec["next_review"] = next_date
            if rec["correct_streak"] >= len(self.intervals):
                rec["mastered"] = True
        else:
            rec["correct_streak"] = 0
            rec["next_review"] = (datetime.now() + timedelta(days=1)).strftime("%Y-%m-%d")
        self.save()

