def load_settings():
    default = {"theme": "dark", "voice": "en-US", "font_size": 14}
    if os.path.exists(SETTINGS_FILE):
        try:
            with open(SETTINGS_FILE, "r", encoding="utf-8") as f:
                default.update(json.load(f))
        except: pass
    return default

