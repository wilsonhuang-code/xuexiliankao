def hex_to_rgba(h):
    m = _re.match(r'#([0-9a-fA-F]{2})([0-9a-fA-F]{2})([0-9a-fA-F]{2})', h)
    if m:
        return (int(m.group(1),16)/255, int(m.group(2),16)/255, int(m.group(3),16)/255, 1)
    return (0.2, 0.2, 0.2, 1)

