            w = self.review_words[self.review_idx]
            meaning = next((m for ww, m, g in ENGLISH_WORDS if ww == w), "")
            self.mastery.mark(w, correct)
            if correct:
                self.review_feedback.text = f"正确! {w} = {meaning}"
                self.review_feedback.color = hex_to_rgba(self.app.get_theme()["success"])
            else:
                self.review_feedback.text = f"正确答案: {meaning}"
                self.review_feedback.color = hex_to_rgba(self.app.get_theme()["error"])
            self.review_idx += 1
            Clock.schedule_once(lambda dt: self.show_review_word(), 1.0)

